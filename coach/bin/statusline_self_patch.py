"""Idempotently install Coach's main statusLine into ~/.claude/settings.json.

Plugin distribution only — Claude Code's plugin model doesn't expose the
top-level `statusLine` key in plugin settings.json (only `agent` and
`subagentStatusLine` are supported per plugins-reference). Workaround:
the plugin's SessionStart hook calls `ensure_statusline_installed()` on
every session start; first call writes the entry, subsequent calls are
O(read).

Why a self-patching approach (vs a one-time companion CLI):
  - Self-healing on plugin install / version-bump.
  - No extra setup step — `/plugin install coach-claw` and the
    statusline appears next session.
  - The cost — `/plugin uninstall coach-claw` does NOT auto-clean the
    settings.json key (Anthropic's plugin lifecycle doesn't touch
    settings.json keys plugins added). `/coach-claw:doctor
    --remove-statusline` covers that path.

Decisions:
  - `${CLAUDE_PLUGIN_ROOT}` is NOT expanded inside settings.json (only
    in plugin's own files). Resolve absolute path at write time.
  - If a `statusLine` already exists pointing at Coach's known marker
    paths, no-op.
  - If a `statusLine` already exists pointing somewhere else (user's
    custom one, another plugin's), DO NOT overwrite. Log via stderr.
  - Atomic write under flock (mirrors merge.py:atomic_write_yaml).
  - CLI distribution: this module is in coach/bin/ for code-share, but
    the CLI's coach-session-start.py never calls into it (CLI manages
    its own statusLine via install.sh). Gating happens at the call
    site via `os.environ.get("CLAUDE_PLUGIN_ROOT")`.
"""
from __future__ import annotations

import fcntl
import json
import os
import shlex
import sys
import tempfile
from pathlib import Path
from typing import Optional


SETTINGS_PATH = Path.home() / ".claude" / "settings.json"

# Stable trampoline filename. Lives under coach_dir (~/.claude/coach/ by
# default) and is generated on every plugin SessionStart by
# ensure_trampoline_installed(). Settings.json statusLine commands point
# at this stable path instead of a versioned plugin install path, so
# `/plugin update` no longer leaves behind a stale-versioned command.
TRAMPOLINE_NAME = "plugin-statusline.sh"
PLUGIN_ROOT_CACHE_NAME = ".plugin-root"
UNINSTALL_PREP_MARKER_NAME = ".uninstall-prepped"


def _drop_uninstall_prep_marker(coach_dir: Path) -> None:
    """Invariant: any write OR observation of a Coach-owned statusLine
    must clear `.uninstall-prepped`.

    The marker means "the user just ran `--uninstall-prep`; the
    upcoming `/plugin uninstall coach-claw@coach-claw-plugins` is
    authorized to bypass the v0.1.20 intercept because the statusLine
    has been cleared." A live Coach-owned statusLine contradicts that
    intent — it means either the marker is stale (SessionStart
    re-installed the entry between prep and uninstall) OR the user
    changed their mind and is using Coach again. Either way, clearing
    the marker re-arms the intercept so a future `/plugin uninstall`
    will warn the user before leaving an orphaned statusLine.

    Fail-soft. Caller is a hook / patcher context; never raise.
    """
    try:
        (coach_dir / UNINSTALL_PREP_MARKER_NAME).unlink()
    except FileNotFoundError:
        pass
    except OSError:
        pass

# Trampoline body. Resolves the active coach-claw plugin install path
# from a small cache file (refreshed every SessionStart), falls back to
# parsing installed_plugins.json on a cold cache. exec preserves stdin,
# which the statusline command receives as a JSON payload.
_TRAMPOLINE_BODY = """#!/usr/bin/env bash
# Coach Claw — stable plugin statusLine trampoline.
# Generated by statusline_self_patch.ensure_trampoline_installed().
# Resolves the active plugin install path at exec time so settings.json
# does not carry a versioned plugin path that goes stale on update.
TARGET="${1:-default_statusline.py}"
COACH_DIR="${COACH_CONFIG_DIR:-$HOME/.claude/coach}"
ROOT_FILE="$COACH_DIR/.plugin-root"

PLUGIN_ROOT=""
if [ -r "$ROOT_FILE" ]; then
  # IFS= preserves embedded spaces inside the path; -r preserves
  # backslashes literally; the bounded < redirect stops at the first
  # newline. tr -d '[:space:]' would have stripped spaces inside a
  # valid filesystem path (e.g. "/Users/some user/.claude/...").
  IFS= read -r PLUGIN_ROOT < "$ROOT_FILE" || true
fi

if [ -z "$PLUGIN_ROOT" ] || [ ! -d "$PLUGIN_ROOT" ]; then
  PLUGIN_ROOT=$(python3 - 2>/dev/null <<'PY' || true
import json, os
from pathlib import Path
p = Path.home() / ".claude" / "plugins" / "installed_plugins.json"
try:
    data = json.loads(p.read_text())
    entries = data.get("plugins", {}).get("coach-claw@coach-claw-plugins", [])
    def parse(v):
        try:
            return tuple(int(x) for x in str(v).split("."))
        except Exception:
            return ()
    if entries:
        best = max(entries, key=lambda e: parse(e.get("version", "")))
        ip = best.get("installPath", "")
        if ip and os.path.isdir(ip):
            print(ip)
except Exception:
    pass
PY
)
fi

[ -n "$PLUGIN_ROOT" ] || exit 0
[ -d "$PLUGIN_ROOT" ] || exit 0

exec "$PLUGIN_ROOT/bin/run.sh" "$PLUGIN_ROOT/bin/$TARGET"
"""

# Substring markers that identify a statusLine command as Coach's. The
# default-shape markers (CLI install via default-statusline-command.sh,
# plugin via default_statusline.py through bootstrap.sh, plugin via the
# stable trampoline) and the wrap-shape markers (statusline_wrap.py for
# plugin, default-statusline-wrap-command.sh for CLI) are all recognized,
# so a user with any combination installed never gets a duplicate or
# overwrite. The trampoline marker is shape-agnostic — both default and
# wrap commands routed through it embed it as argv[0].
COACH_STATUSLINE_MARKERS = (
    "default-statusline-command.sh",
    "default_statusline.py",
    "statusline_wrap.py",
    "default-statusline-wrap-command.sh",
    TRAMPOLINE_NAME,
)

# Subset of the markers above that identify the WRAP shape specifically.
# Lets `ensure_statusline_installed` route ours-wrapped through a path-
# freshness refresh instead of the simple matched no-op.
_WRAP_STATUSLINE_MARKERS = (
    "statusline_wrap.py",
    "default-statusline-wrap-command.sh",
)


def _is_coach_statusline(entry) -> bool:
    if not isinstance(entry, dict):
        return False
    cmd = str(entry.get("command", ""))
    return any(m in cmd for m in COACH_STATUSLINE_MARKERS)


def _is_wrap_statusline(entry) -> bool:
    if not isinstance(entry, dict):
        return False
    cmd = str(entry.get("command", ""))
    return any(m in cmd for m in _WRAP_STATUSLINE_MARKERS)


def _is_trampoline_command(cmd: str) -> bool:
    return TRAMPOLINE_NAME in cmd


def ensure_trampoline_installed(coach_dir: Path, plugin_root: Path) -> Path:
    """Write the stable plugin statusLine trampoline + .plugin-root cache.

    Idempotent. Returns the absolute trampoline path. Both files are
    written under `coach_dir` so they survive `/plugin update` cycles
    that swap the cache-dir version path.

    Failures are silent (caller is the SessionStart hook, which must
    never raise). On a write error the caller falls back to the prior
    behavior of writing the versioned path directly.
    """
    coach_dir.mkdir(parents=True, exist_ok=True)

    # 1. .plugin-root cache file — current active plugin install path.
    root_file = coach_dir / PLUGIN_ROOT_CACHE_NAME
    desired_root = str(Path(plugin_root).resolve())
    try:
        current_root = root_file.read_text().strip() if root_file.exists() else None
    except Exception:
        current_root = None
    if current_root != desired_root:
        try:
            tmp = root_file.with_suffix(root_file.suffix + ".tmp")
            tmp.write_text(desired_root + "\n")
            os.replace(tmp, root_file)
        except Exception:
            pass

    # 2. Trampoline shell script.
    trampoline = coach_dir / TRAMPOLINE_NAME
    try:
        current_body = trampoline.read_text() if trampoline.exists() else None
    except Exception:
        current_body = None
    if current_body != _TRAMPOLINE_BODY:
        try:
            tmp = trampoline.with_suffix(trampoline.suffix + ".tmp")
            tmp.write_text(_TRAMPOLINE_BODY)
            os.replace(tmp, trampoline)
        except Exception:
            pass
        try:
            trampoline.chmod(0o755)
        except Exception:
            pass

    return trampoline


def _desired_entry(plugin_root: Path, coach_dir: Optional[Path] = None) -> dict:
    """Build the statusLine entry for the plugin distribution.

    Prefers the stable trampoline path under `coach_dir` (set by
    `ensure_trampoline_installed`). Falls back to the legacy versioned
    `run.sh <plugin_root>/bin/default_statusline.py` shape only when
    `coach_dir` is None (callers that haven't been migrated yet).
    """
    if coach_dir is not None:
        trampoline = shlex.quote(str(coach_dir / TRAMPOLINE_NAME))
        return {
            "type": "command",
            "command": f"bash {trampoline} default_statusline.py",
        }
    run_sh = shlex.quote(str(plugin_root / "bin" / "run.sh"))
    statusline_py = shlex.quote(str(plugin_root / "bin" / "default_statusline.py"))
    return {
        "type": "command",
        "command": f"{run_sh} {statusline_py}",
    }


def _atomic_write(path: Path, payload: dict) -> None:
    """tempfile + os.replace under flock — same pattern as merge.py."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lock_path = path.with_suffix(path.suffix + ".lock")
    with open(lock_path, "w") as lock_fh:
        try:
            fcntl.flock(lock_fh.fileno(), fcntl.LOCK_EX)
        except Exception:
            pass  # flock unsupported — proceed best-effort
        fd, tmp = tempfile.mkstemp(
            prefix="." + path.name + ".",
            suffix=".tmp",
            dir=str(path.parent),
        )
        try:
            with os.fdopen(fd, "w") as fh:
                json.dump(payload, fh, indent=2)
                fh.flush()
                os.fsync(fh.fileno())
            os.replace(tmp, path)
        except Exception:
            try:
                os.unlink(tmp)
            except Exception:
                pass
            raise


def ensure_statusline_installed(
    plugin_root: str,
    settings_path: Optional[Path] = None,
    coach_dir: Optional[Path] = None,
) -> str:
    """Idempotently set Coach's statusLine in `settings_path`.

    Returns one of:
        "installed"      — wrote a new entry (was absent).
        "matched"        — already present and ours; no write.
        "refreshed-path" — ours-default with stale legacy versioned path;
                           rewrote to point at the stable trampoline.
        "wrap-refreshed" — ours-wrapped with stale plugin path; rewrote
                           with current trampoline path.
        "wrapped"        — auto-wrapped a user's claimed statusline so
                           the Coach segment now appends to it.
        "claimed"        — present pointing at someone else AND auto-
                           wrap was suppressed (opt-out marker or manual
                           Coach integration detected).
        "skipped"        — settings.json doesn't exist (very fresh user;
                           Claude Code creates it on first run).
        "error"          — exception during read/write (always fail-soft).

    `settings_path` defaults to ~/.claude/settings.json; tests pass a
    tmpdir path. `coach_dir` defaults to `coach_paths.resolve_coach_dir()`;
    tests pass a tmpdir.
    """
    target = settings_path or SETTINGS_PATH
    try:
        if coach_dir is None:
            # Imported lazily so importing this module from a context
            # without coach_paths on sys.path (some test harnesses) still
            # works when callers pass coach_dir explicitly.
            try:
                from coach_paths import resolve_coach_dir  # noqa: WPS433
                coach_dir = resolve_coach_dir()
            except Exception:
                coach_dir = Path.home() / ".claude" / "coach"

        plugin_root_p = Path(plugin_root).resolve()

        # Always (re)write the trampoline + .plugin-root cache first. This
        # is what keeps settings.json's command stable across plugin
        # updates: the command path stays the same, only the cached
        # plugin install path under coach_dir moves.
        ensure_trampoline_installed(coach_dir, plugin_root_p)

        if not target.exists():
            return "skipped"

        try:
            data = json.loads(target.read_text())
        except json.JSONDecodeError:
            return "error"
        if not isinstance(data, dict):
            return "error"

        existing = data.get("statusLine")
        if existing:
            # Wrap shape — delegate to the action module so path-freshness
            # refresh and idempotency live in one place.
            if _is_wrap_statusline(existing):
                try:
                    import statusline_wrap_action as wa  # noqa: WPS433
                    res = wa.wrap(
                        settings_path=target,
                        plugin_root=plugin_root_p,
                        coach_dir=coach_dir,
                    )
                except Exception:
                    # fail-soft; no rewrite happened, but a Coach wrap
                    # shape was observed — invalidate any stale prep marker.
                    _drop_uninstall_prep_marker(coach_dir)
                    return "matched"
                _drop_uninstall_prep_marker(coach_dir)
                if res.get("reason") == "refreshed-path":
                    return "wrap-refreshed"
                return "matched"
            if _is_coach_statusline(existing):
                # Migrate any non-trampoline plugin shape to the stable
                # trampoline path. Covers two legacy shapes:
                #   1. v0.1.18+ `<plugin>/bin/run.sh <plugin>/bin/default_statusline.py`
                #      — versioned path, goes stale on /plugin update.
                #   2. Earlier `<plugin>/bin/bootstrap.sh <plugin>/bin/default_statusline.py`
                #      — same staleness plus coexistence-guard issue.
                # The CLI's `default-statusline-command.sh` shape stays
                # untouched (different marker, owned by install.sh).
                existing_cmd = str(existing.get("command", ""))
                is_legacy_plugin_default = (
                    "default_statusline.py" in existing_cmd
                    and not _is_trampoline_command(existing_cmd)
                )
                if is_legacy_plugin_default:
                    data["statusLine"] = _desired_entry(
                        plugin_root_p, coach_dir=coach_dir
                    )
                    _atomic_write(target, data)
                    _drop_uninstall_prep_marker(coach_dir)
                    return "refreshed-path"
                # Matched: an already-current Coach statusLine. Observation
                # alone invalidates the uninstall-prep marker — a stale
                # marker plus a Coach-owned statusLine is already the
                # broken state the v0.1.20 intercept was meant to prevent.
                _drop_uninstall_prep_marker(coach_dir)
                return "matched"

            # Claimed: auto-wrap on first encounter, unless opted out or
            # manual-Coach integration detected. wrap_action.wrap()
            # handles both gates internally and falls through to a wrap
            # mutation on success.
            try:
                import statusline_wrap_action as wa  # noqa: WPS433
                res = wa.wrap(
                    settings_path=target,
                    plugin_root=plugin_root_p,
                    coach_dir=coach_dir,
                )
            except Exception:
                res = {"result": "error"}
            if res.get("result") == "wrapped":
                _drop_uninstall_prep_marker(coach_dir)
                return "wrapped"
            sys.stderr.write(
                "coach-claw plugin: settings.json statusLine left "
                "untouched. Run /coach-claw:doctor to inspect.\n"
            )
            return "claimed"

        data["statusLine"] = _desired_entry(plugin_root_p, coach_dir=coach_dir)
        _atomic_write(target, data)
        _drop_uninstall_prep_marker(coach_dir)
        return "installed"
    except Exception:
        return "error"
